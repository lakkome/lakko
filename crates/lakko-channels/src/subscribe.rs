//! Subscriber-path crypto for Phase 4b channels.
//!
//! Per ADR-0010 §"Tier 2 — Sender-key broadcast" — a
//! publisher seals the channel's 32-byte `content_key_seed`
//! against each subscriber's key. The subscriber opens with
//! its secret and installs the seed into [`ContentKeySeed`],
//! from which [`crate::post::verify_and_decrypt`] takes over.
//!
//! ## One subscriber key: Ed25519 ([ADR-0058] section 3)
//!
//! A subscriber holds ONE Ed25519 key pair. Its public key is
//! the subscriber identifier everywhere: the registration, the
//! envelope path, the member-card binding
//! ([`crate::member_card`]) and the key a member-card upload is
//! signed with. The X25519 key the seed envelope is sealed to
//! is derived from it (`lakko_crypto::signing`,
//! [`SigningKey::to_x25519_secret`] /
//! [`VerifyingKey::to_x25519_public`], the libsodium
//! `ed25519_*_to_curve25519` mapping), so the key a subscriber
//! signs with and the key it receives the seed under are one
//! registered value. A key that is not a valid Ed25519 point,
//! or is of small order, is refused ([`subscriber_public_key`]).
//!
//! [ADR-0058]: ../../../docs/adr/0058-scoped-discovery.md
//!
//! ## Wire shape
//!
//! ```text
//! SeedEnvelope := eph_pub(32) || ciphertext_with_tag
//! ```
//!
//! `eph_pub` is a single-use X25519 public key generated by
//! the sealer; the recipient combines it with their own
//! static X25519 secret to recover the AEAD key. AAD binds
//! `channel_id || epoch_id` so a misrouted envelope to
//! the wrong channel or wrong epoch fails the AEAD
//! authenticator — the subscriber sees a clean rejection,
//! not a wrong-seed install.
//!
//! ## Construction
//!
//! 1. Sealer generates an ephemeral X25519 keypair
//!    `(eph_priv, eph_pub)`.
//! 2. `shared = ECDH(eph_priv, subscriber_pub)`.
//! 3. `key = HKDF-SHA-256(salt = "", ikm = shared,
//!    info = "lakko/channel/v1/seed-envelope/key" || eph_pub)`.
//! 4. `nonce = HKDF-SHA-256(salt = "", ikm = shared,
//!    info = "lakko/channel/v1/seed-envelope/nonce" || eph_pub)`.
//! 5. `aad = channel_id || epoch_id_be`.
//! 6. AEAD `seal(key, nonce, aad, seed_bytes)`.
//! 7. Wire = `eph_pub || ciphertext_with_tag`.
//!
//! Properties:
//!
//! - **Forward secrecy (sender-side)** — `eph_priv` is
//!   discarded after seal. A future compromise of the
//!   subscriber's long-term X25519 private key still
//!   decrypts past envelopes — that's the inherent HPKE-
//!   Base-mode property; backward secrecy on channel
//!   content is the ADR-0010 trade-off and is mitigated
//!   by aggressive rotation, not by envelope FS.
//! - **No sender-authentication** at the envelope layer.
//!   The Ed25519 signature on every `ChannelPost`
//!   (`POST_SIG_DOMAIN_V1`) is what proves provenance once
//!   the recipient has installed the seed. A forged seed
//!   envelope from a non-publisher just installs the wrong
//!   seed — every subsequent post fails to verify.
//! - **Domain separation** — labels carry
//!   `"lakko/channel/v1/seed-envelope"` so a future
//!   protocol variant (`v2`, channel-rotation envelopes,
//!   etc.) cannot collide on HKDF outputs.

use lakko_crypto::aead::{self, AeadKey, Algorithm, Nonce, KEY_LEN, NONCE_LEN};
use lakko_crypto::agreement::{PublicKey, SecretKey};
use lakko_crypto::kdf::hkdf_sha256;
use lakko_crypto::secret::SecretBytes;
use lakko_crypto::signing::{SigningKey, VerifyingKey};

use crate::epoch::EpochId;
use crate::error::{ChannelError, Result};
use crate::member_card::SUBSCRIBER_PK_LEN;
use crate::seed::{ContentKeySeed, CONTENT_KEY_SEED_LEN};
use crate::CHANNEL_ID_LEN;

/// Length of the ephemeral X25519 public-key prefix on the
/// wire (32 bytes).
pub const EPH_PUB_LEN: usize = 32;

/// Length of the trailing AEAD authentication tag
/// (ChaCha20-Poly1305 → 16 bytes).
pub const TAG_LEN: usize = aead::TAG_LEN;

/// Total wire length of a [`SeedEnvelope`] —
/// `eph_pub + sealed_seed + tag`.
pub const SEED_ENVELOPE_LEN: usize = EPH_PUB_LEN + CONTENT_KEY_SEED_LEN + TAG_LEN;

/// HKDF info label for the AEAD key. Frozen at v1.
const HKDF_INFO_KEY: &[u8] = b"lakko/channel/v1/seed-envelope/key";
/// HKDF info label for the AEAD nonce. Frozen at v1.
const HKDF_INFO_NONCE: &[u8] = b"lakko/channel/v1/seed-envelope/nonce";

/// AEAD ciphersuite — matches [`crate::post`]: ChaCha20-
/// Poly1305 is the Lakko default; AES-256-GCM is a
/// separate variant left to a future enum bump if FIPS
/// becomes a requirement.
const ALG: Algorithm = Algorithm::ChaCha20Poly1305;

/// Parse and validate a subscriber key: a valid Ed25519
/// point of more than small order. The one check the
/// registration, the seal and a member-card signature all
/// apply.
///
/// # Errors
///
/// [`ChannelError::BadSubscriberKey`] for a wrong length, an
/// encoding that is not a curve point, or a small-order point.
pub fn subscriber_public_key(bytes: &[u8]) -> Result<VerifyingKey> {
    if bytes.len() != SUBSCRIBER_PK_LEN {
        return Err(ChannelError::BadSubscriberKey);
    }
    let key = VerifyingKey::from_bytes(bytes).map_err(|_| ChannelError::BadSubscriberKey)?;
    if key.is_weak() {
        return Err(ChannelError::BadSubscriberKey);
    }
    Ok(key)
}

/// Seal a 32-byte content-key seed against a subscriber's
/// Ed25519 public key (converted to X25519, see the module
/// docs). Returns the on-wire bytes:
/// `eph_pub(32) || ciphertext_with_tag`.
///
/// # Errors
///
/// Returns [`ChannelError::BadSubscriberKey`] when the key is
/// not a valid Ed25519 point or is of small order,
/// [`ChannelError::KeyDerivation`] on HKDF failure
/// (cannot happen with current fixed sizes) and
/// [`ChannelError::AeadSeal`] on AEAD seal failure
/// (impossible with ChaCha20-Poly1305 + valid lengths;
/// surfaced for completeness).
pub fn seal_seed(
    subscriber_pk: &[u8; SUBSCRIBER_PK_LEN],
    channel_id: &[u8; CHANNEL_ID_LEN],
    epoch_id: EpochId,
    seed: &ContentKeySeed,
) -> Result<Vec<u8>> {
    let subscriber_pub = subscriber_public_key(subscriber_pk)?.to_x25519_public();
    seal_seed_to_x25519(&subscriber_pub, channel_id, epoch_id, seed)
}

fn seal_seed_to_x25519(
    subscriber_pub: &PublicKey,
    channel_id: &[u8; CHANNEL_ID_LEN],
    epoch_id: EpochId,
    seed: &ContentKeySeed,
) -> Result<Vec<u8>> {
    let eph_priv = SecretKey::generate();
    let eph_pub = eph_priv.public_key();
    let shared = eph_priv.diffie_hellman(subscriber_pub);

    let eph_pub_bytes = eph_pub.to_bytes();
    let (key, nonce) = derive_key_and_nonce(&shared, &eph_pub_bytes)?;
    let aad = make_aad(channel_id, epoch_id);
    let ciphertext = aead::seal(ALG, &key, &nonce, &aad, seed.as_inner_bytes())
        .map_err(|_| ChannelError::AeadSeal)?;

    let mut out = Vec::with_capacity(EPH_PUB_LEN + ciphertext.len());
    out.extend_from_slice(&eph_pub_bytes);
    out.extend_from_slice(&ciphertext);
    Ok(out)
}

/// Open a seed envelope with the subscriber's Ed25519 key
/// (its X25519 secret derived, see the module docs). Returns
/// the recovered seed wrapped in [`ContentKeySeed`] — the
/// public API never exposes the raw bytes.
///
/// # Errors
///
/// - [`ChannelError::Wire`] — buffer is shorter than
///   `EPH_PUB_LEN + TAG_LEN` or the ephemeral pubkey
///   parse fails.
/// - [`ChannelError::AeadOpen`] — wrong secret, wrong
///   `(channel_id, epoch_id)` binding, or tampered
///   ciphertext.
/// - [`ChannelError::KeyDerivation`] — HKDF refused.
/// - [`ChannelError::SeedLength`] — decrypted plaintext
///   was not exactly 32 bytes (would only happen if a
///   future schema bump changed the seed size without
///   bumping the envelope label).
pub fn open_seed(
    subscriber_key: &SigningKey,
    channel_id: &[u8; CHANNEL_ID_LEN],
    epoch_id: EpochId,
    wire: &[u8],
) -> Result<ContentKeySeed> {
    let subscriber_priv = subscriber_key.to_x25519_secret();
    if wire.len() < EPH_PUB_LEN + TAG_LEN {
        return Err(ChannelError::Wire("seed envelope shorter than minimum"));
    }
    let (eph_pub_bytes, ciphertext) = wire.split_at(EPH_PUB_LEN);

    let mut eph_arr = [0u8; EPH_PUB_LEN];
    eph_arr.copy_from_slice(eph_pub_bytes);
    let eph_pub = PublicKey::from_bytes(&eph_arr)
        .map_err(|_| ChannelError::Wire("seed envelope ephemeral pubkey invalid"))?;

    let shared = subscriber_priv.diffie_hellman(&eph_pub);
    let (key, nonce) = derive_key_and_nonce(&shared, &eph_arr)?;
    let aad = make_aad(channel_id, epoch_id);
    let plaintext =
        aead::open(ALG, &key, &nonce, &aad, ciphertext).map_err(|_| ChannelError::AeadOpen)?;
    ContentKeySeed::from_exporter_output(&plaintext)
}

// ----------------------------------------------------------------
// Internal helpers — pinned crypto contract.
// ----------------------------------------------------------------

fn make_aad(channel_id: &[u8; CHANNEL_ID_LEN], epoch_id: EpochId) -> Vec<u8> {
    let mut aad = Vec::with_capacity(CHANNEL_ID_LEN + 4);
    aad.extend_from_slice(channel_id);
    aad.extend_from_slice(&epoch_id.to_be_bytes());
    aad
}

fn derive_key_and_nonce(
    shared: &SecretBytes<32>,
    eph_pub_bytes: &[u8; EPH_PUB_LEN],
) -> Result<(AeadKey, Nonce)> {
    // Bind the eph_pub into both info strings so two
    // envelopes that happen to share the same DH output
    // (one-in-a-cosmos but still — domain-separated by
    // construction) cannot collide on key/nonce.
    let mut info_key = Vec::with_capacity(HKDF_INFO_KEY.len() + EPH_PUB_LEN);
    info_key.extend_from_slice(HKDF_INFO_KEY);
    info_key.extend_from_slice(eph_pub_bytes);
    let key = hkdf_sha256::<KEY_LEN>(shared.as_bytes(), &[], &info_key)
        .map_err(|_| ChannelError::KeyDerivation)?;

    let mut info_nonce = Vec::with_capacity(HKDF_INFO_NONCE.len() + EPH_PUB_LEN);
    info_nonce.extend_from_slice(HKDF_INFO_NONCE);
    info_nonce.extend_from_slice(eph_pub_bytes);
    let nonce_secret = hkdf_sha256::<NONCE_LEN>(shared.as_bytes(), &[], &info_nonce)
        .map_err(|_| ChannelError::KeyDerivation)?;
    let mut nonce = [0u8; NONCE_LEN];
    nonce.copy_from_slice(nonce_secret.as_bytes());
    Ok((key, nonce))
}

#[cfg(test)]
mod tests {
    use super::*;

    const CHANNEL: [u8; CHANNEL_ID_LEN] = *b"channel-id-16byt";

    fn fixture_seed() -> ContentKeySeed {
        ContentKeySeed::from_bytes_for_test([0x33; CONTENT_KEY_SEED_LEN])
    }

    #[test]
    fn round_trip_seal_open() {
        let sub = SigningKey::generate();
        let seed = fixture_seed();
        let env = seal_seed(
            &sub.verifying_key().to_bytes(),
            &CHANNEL,
            EpochId::new(1),
            &seed,
        )
        .unwrap();
        let recovered = open_seed(&sub, &CHANNEL, EpochId::new(1), &env).unwrap();
        assert_eq!(recovered, seed);
    }

    #[test]
    fn envelope_size_matches_constant() {
        let sub = SigningKey::generate();
        let seed = fixture_seed();
        let env = seal_seed(
            &sub.verifying_key().to_bytes(),
            &CHANNEL,
            EpochId::new(1),
            &seed,
        )
        .unwrap();
        assert_eq!(env.len(), SEED_ENVELOPE_LEN);
    }

    #[test]
    fn wrong_subscriber_key_fails() {
        let sub = SigningKey::generate();
        let other = SigningKey::generate();
        let seed = fixture_seed();
        let env = seal_seed(
            &sub.verifying_key().to_bytes(),
            &CHANNEL,
            EpochId::new(1),
            &seed,
        )
        .unwrap();
        let err = open_seed(&other, &CHANNEL, EpochId::new(1), &env).unwrap_err();
        assert!(matches!(err, ChannelError::AeadOpen));
    }

    #[test]
    fn wrong_channel_id_fails() {
        let sub = SigningKey::generate();
        let other_channel = *b"OTHER-CHAN-ID-16";
        let seed = fixture_seed();
        let env = seal_seed(
            &sub.verifying_key().to_bytes(),
            &CHANNEL,
            EpochId::new(1),
            &seed,
        )
        .unwrap();
        let err = open_seed(&sub, &other_channel, EpochId::new(1), &env).unwrap_err();
        assert!(matches!(err, ChannelError::AeadOpen));
    }

    #[test]
    fn wrong_epoch_fails() {
        let sub = SigningKey::generate();
        let seed = fixture_seed();
        let env = seal_seed(
            &sub.verifying_key().to_bytes(),
            &CHANNEL,
            EpochId::new(1),
            &seed,
        )
        .unwrap();
        let err = open_seed(&sub, &CHANNEL, EpochId::new(2), &env).unwrap_err();
        assert!(matches!(err, ChannelError::AeadOpen));
    }

    #[test]
    fn tampered_ciphertext_fails() {
        let sub = SigningKey::generate();
        let seed = fixture_seed();
        let mut env = seal_seed(
            &sub.verifying_key().to_bytes(),
            &CHANNEL,
            EpochId::new(1),
            &seed,
        )
        .unwrap();
        // Flip a byte in the ciphertext (just past the
        // ephemeral pubkey prefix).
        env[EPH_PUB_LEN] ^= 0xFF;
        let err = open_seed(&sub, &CHANNEL, EpochId::new(1), &env).unwrap_err();
        assert!(matches!(err, ChannelError::AeadOpen));
    }

    #[test]
    fn tampered_ephemeral_pubkey_fails() {
        let sub = SigningKey::generate();
        let seed = fixture_seed();
        let mut env = seal_seed(
            &sub.verifying_key().to_bytes(),
            &CHANNEL,
            EpochId::new(1),
            &seed,
        )
        .unwrap();
        // Flip the high byte of the ephemeral pubkey. The
        // DH output changes, the HKDF key/nonce change,
        // and the AEAD authenticator rejects.
        env[0] ^= 0x01;
        let err = open_seed(&sub, &CHANNEL, EpochId::new(1), &env).unwrap_err();
        assert!(matches!(err, ChannelError::AeadOpen));
    }

    #[test]
    fn too_short_buffer_fails() {
        let sub = SigningKey::generate();
        let err = open_seed(&sub, &CHANNEL, EpochId::new(0), &[0u8; 10]).unwrap_err();
        assert!(matches!(err, ChannelError::Wire(_)));
    }

    #[test]
    fn two_subscribers_get_distinct_envelopes_for_same_seed() {
        // Two different recipients → two different
        // ephemeral pubkeys + two different ECDH shared
        // outputs → two distinct ciphertexts. Sanity that
        // the publisher's "fan-out one seed to N
        // subscribers" path produces N independent
        // envelopes.
        let sub_a = SigningKey::generate();
        let sub_b = SigningKey::generate();
        let seed = fixture_seed();
        let env_a = seal_seed(
            &sub_a.verifying_key().to_bytes(),
            &CHANNEL,
            EpochId::new(5),
            &seed,
        )
        .unwrap();
        let env_b = seal_seed(
            &sub_b.verifying_key().to_bytes(),
            &CHANNEL,
            EpochId::new(5),
            &seed,
        )
        .unwrap();
        assert_ne!(env_a, env_b);
        // Both still open to the same seed.
        let a = open_seed(&sub_a, &CHANNEL, EpochId::new(5), &env_a).unwrap();
        let b = open_seed(&sub_b, &CHANNEL, EpochId::new(5), &env_b).unwrap();
        assert_eq!(a, seed);
        assert_eq!(b, seed);
    }

    #[test]
    fn cross_recipient_envelope_rejected() {
        // Two subscribers, but try to open A's envelope
        // with B's key — must fail at the AEAD layer.
        let sub_a = SigningKey::generate();
        let sub_b = SigningKey::generate();
        let seed = fixture_seed();
        let env_a = seal_seed(
            &sub_a.verifying_key().to_bytes(),
            &CHANNEL,
            EpochId::new(1),
            &seed,
        )
        .unwrap();
        let err = open_seed(&sub_b, &CHANNEL, EpochId::new(1), &env_a).unwrap_err();
        assert!(matches!(err, ChannelError::AeadOpen));
    }

    #[test]
    fn the_envelope_is_sealed_to_the_x25519_image_of_the_subscriber_key() {
        // A publisher sealing straight to the converted X25519 key produces
        // an envelope the subscriber opens with its Ed25519 key: the
        // conversion is the whole binding.
        let sub = SigningKey::generate();
        let seed = fixture_seed();
        let x = sub.verifying_key().to_x25519_public();
        let env = seal_seed_to_x25519(&x, &CHANNEL, EpochId::new(1), &seed).unwrap();
        assert_eq!(
            open_seed(&sub, &CHANNEL, EpochId::new(1), &env).unwrap(),
            seed
        );
    }

    #[test]
    fn invalid_and_small_order_subscriber_keys_are_refused() {
        let seed = fixture_seed();
        // The identity point: decodes, order 1.
        let mut identity = [0u8; 32];
        identity[0] = 1;
        // y = 2 is not on the curve (no x satisfies the equation).
        let mut off_curve = [0u8; 32];
        off_curve[0] = 2;
        for bad in [identity, off_curve] {
            assert!(matches!(
                seal_seed(&bad, &CHANNEL, EpochId::new(1), &seed),
                Err(ChannelError::BadSubscriberKey)
            ));
            assert!(matches!(
                subscriber_public_key(&bad),
                Err(ChannelError::BadSubscriberKey)
            ));
        }
        assert!(matches!(
            subscriber_public_key(&[0u8; 31]),
            Err(ChannelError::BadSubscriberKey)
        ));
        let good = SigningKey::generate().verifying_key().to_bytes();
        assert!(subscriber_public_key(&good).is_ok());
    }

    #[test]
    fn label_constants_pinned() {
        // The label strings are part of the protocol's
        // domain separation surface — a refactor that
        // bumps them to v2 without renaming would silently
        // break wire compatibility with previously-shipped
        // clients. Pin the bytes here.
        assert_eq!(HKDF_INFO_KEY, b"lakko/channel/v1/seed-envelope/key");
        assert_eq!(HKDF_INFO_NONCE, b"lakko/channel/v1/seed-envelope/nonce");
    }
}
