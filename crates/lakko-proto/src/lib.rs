//! Generated protobuf types for Lakko wire format.
//!
//! All wire types are generated from `schemas/` via `just regen-proto`.
//! Hand-written code in this crate is limited to thin convenience helpers
//! (e.g. `From` impls between domain types and proto types).
//!
//! Generated code lives under `src/generated/` and is committed to the repo
//! so consumers do not need a `protoc` toolchain.

