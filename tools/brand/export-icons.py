"""Export the Lakko in-app icon set to the three clients.

Source of truth: docs/brand/icons/svg/<name>.svg (design system section 8).
Writes, replacing what an earlier run wrote:

- Android: apps/android/app/src/main/res/drawable/ic_lk_<name>.xml
  (VectorDrawable, black, tinted by the caller; `-` becomes `_`).
- iOS: apps/ios/Lakko/Assets.xcassets/Icons/<name>.imageset (the SVG with
  currentColor made black, template rendering, vector data preserved; the
  folder provides the namespace, so the asset is "Icons/<name>"), and
  apps/ios/Lakko/UI/LkIcon.generated.swift (one case per icon).
- Web: apps/web/src/ui/icon-paths.generated.ts (inner SVG markup per icon;
  stroke paths inherit the wrapper's stroke, filled paths carry their fill).

Icons that point in the reading direction are mirrored in right-to-left
languages on every client (design system, "Mirroring").

Run from the repository root: `python3 tools/brand/export-icons.py`
(`just export-icons`). Python 3 standard library only.
"""
import json
import os
import re
import shutil
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "docs/brand/icons/svg")
ANDROID = os.path.join(ROOT, "apps/android/app/src/main/res/drawable")
IOS_SET = os.path.join(ROOT, "apps/ios/Lakko/Assets.xcassets/Icons")
IOS_SWIFT = os.path.join(ROOT, "apps/ios/Lakko/UI/LkIcon.generated.swift")
WEB_TS = os.path.join(ROOT, "apps/web/src/ui/icon-paths.generated.ts")

MIRRORED = {"chevron-back", "chevron-forward", "reply", "forward", "send", "send-fill",
            "logout", "arrow-up-right"}
STROKE_WIDTH = "1.75"
SVG_NS = "{http://www.w3.org/2000/svg}"
NAME_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
HEADER = "Generated by tools/brand/export-icons.py from docs/brand/icons/svg. Do not edit."


def fail(msg):
    sys.stderr.write(f"export-icons: {msg}\n")
    sys.exit(1)


def read_icon(name):
    """The icon's paths as (kind, d): kind is 's' (stroke), 'fs' (fill and stroke) or 'f' (fill)."""
    tree = ET.parse(os.path.join(SRC, name + ".svg"))
    svg = tree.getroot()
    if svg.get("viewBox") != "0 0 24 24":
        fail(f"{name}: viewBox must be 0 0 24 24")
    out = []
    for el in svg:
        tag = el.tag.replace(SVG_NS, "")
        if tag != "path":
            fail(f"{name}: only <path> elements are allowed, found <{tag}>")
        d = el.get("d", "")
        if not d or re.search(r"[a-z]", re.sub(r"[eE][-+]?\d", "", d)):
            fail(f"{name}: path data must use absolute commands only")
        fill, stroke = el.get("fill", "none"), el.get("stroke", "none")
        if fill not in ("none", "currentColor") or stroke not in ("none", "currentColor"):
            fail(f"{name}: only currentColor is allowed")
        if stroke == "currentColor" and el.get("stroke-width") != STROKE_WIDTH:
            fail(f"{name}: stroke width must be {STROKE_WIDTH}")
        if fill == "currentColor" and el.get("fill-rule") != "evenodd":
            fail(f"{name}: a filled path must use fill-rule evenodd")
        if fill == "none" and stroke == "currentColor":
            out.append(("s", d))
        elif fill == "currentColor" and stroke == "currentColor":
            out.append(("fs", d))
        elif fill == "currentColor":
            out.append(("f", d))
        else:
            fail(f"{name}: a path draws nothing")
    if not out:
        fail(f"{name}: no paths")
    return out


def android(name, paths):
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             "<!-- SPDX-License-Identifier: AGPL-3.0-or-later -->",
             "<!-- SPDX-FileCopyrightText: 2026 Lakko Contributors -->",
             f"<!-- {HEADER} -->",
             '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
             '    android:width="24dp"',
             '    android:height="24dp"',
             '    android:viewportWidth="24"',
             '    android:viewportHeight="24"' + (
                 '\n    android:autoMirrored="true">' if name in MIRRORED else ">")]
    for kind, d in paths:
        attrs = [f'android:pathData="{d}"']
        if kind in ("fs", "f"):
            attrs += ['android:fillColor="#FF000000"', 'android:fillType="evenOdd"']
        if kind in ("s", "fs"):
            attrs += ['android:strokeColor="#FF000000"', f'android:strokeWidth="{STROKE_WIDTH}"',
                      'android:strokeLineCap="round"', 'android:strokeLineJoin="round"']
        lines.append("    <path\n        " + "\n        ".join(attrs) + " />")
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def ios_svg(name):
    text = open(os.path.join(SRC, name + ".svg")).read()
    return text.replace("currentColor", "#000000")


def ios_contents(name):
    image = {"filename": f"{name}.svg", "idiom": "universal"}
    if name in MIRRORED:
        image["language-direction"] = "left-to-right"
    return json.dumps({"images": [image], "info": {"author": "xcode", "version": 1},
                       "properties": {"preserves-vector-representation": True,
                                      "template-rendering-intent": "template"}}, indent=2) + "\n"


def camel(name):
    head, *rest = name.split("-")
    out = head + "".join(p[:1].upper() + p[1:] for p in rest)
    return "_" + out if out[0].isdigit() else out


def swift(names):
    cases = "\n".join(f'    case {camel(n)} = "{n}"' for n in names)
    mirrored = ", ".join(f".{camel(n)}" for n in sorted(MIRRORED))
    return f"""// SPDX-License-Identifier: AGPL-3.0-or-later
// SPDX-FileCopyrightText: 2026 Lakko Contributors
// {HEADER}

import SwiftUI

/// The Lakko in-app icon set (design system section 8): one case per icon in
/// `docs/brand/icons/svg`, drawn from the "Icons" folder of the asset catalog
/// as a template image (tinted by the foreground style).
enum LkIcon: String, CaseIterable, Sendable {{
{cases}

    /// The asset-catalog name.
    var assetName: String {{ "Icons/" + rawValue }}

    /// The icon as a resizable template image.
    var image: Image {{ Image(assetName).renderingMode(.template).resizable() }}

    /// Whether the icon points in the reading direction (mirrored right to left;
    /// the asset catalog mirrors these by itself).
    var mirrorsInRightToLeft: Bool {{ Self.mirrored.contains(self) }}

    private static let mirrored: Set<LkIcon> = [{mirrored}]
}}
"""


def web(icons):
    entries = []
    for name, paths in icons:
        parts = []
        for kind, d in paths:
            if kind == "s":
                parts.append(f'<path d="{d}"/>')
            elif kind == "fs":
                parts.append(f'<path d="{d}" fill="currentColor" fill-rule="evenodd"/>')
            else:
                parts.append(f'<path d="{d}" fill="currentColor" fill-rule="evenodd" stroke="none"/>')
        entries.append(f'  "{name}": `{"".join(parts)}`,')
    mirrored = ", ".join(f'"{n}"' for n in sorted(MIRRORED))
    return (f"""// SPDX-License-Identifier: AGPL-3.0-or-later
// SPDX-FileCopyrightText: 2026 Lakko Contributors
// {HEADER}

/**
 * Inner SVG markup of every icon in the Lakko set (design system section 8),
 * on a 24 x 24 viewBox. Stroke paths inherit the wrapper's `stroke`
 * (currentColor, 1.75, round caps and joins) and `fill="none"`; filled paths
 * carry their own even-odd fill.
 */
export const LK_ICON_PATHS = {{
""" + "\n".join(entries) + f"""
}} as const;

/** Icons mirrored in right-to-left languages (they point in the reading direction). */
export const LK_ICON_MIRRORED: ReadonlySet<string> = new Set([{mirrored}]);

/** The stroke width every icon is drawn with. */
export const LK_ICON_STROKE_WIDTH = {STROKE_WIDTH};
""")


def main():
    names = sorted(n[:-4] for n in os.listdir(SRC) if n.endswith(".svg"))
    for n in names:
        if not NAME_RE.match(n):
            fail(f"{n}: names are kebab-case")
    missing = MIRRORED - set(names)
    if missing:
        fail(f"mirrored icons not in the set: {sorted(missing)}")
    icons = [(n, read_icon(n)) for n in names]

    for f in os.listdir(ANDROID):
        if f.startswith("ic_lk_") and f.endswith(".xml"):
            os.remove(os.path.join(ANDROID, f))
    for n, paths in icons:
        with open(os.path.join(ANDROID, "ic_lk_" + n.replace("-", "_") + ".xml"), "w") as f:
            f.write(android(n, paths))

    if os.path.isdir(IOS_SET):
        shutil.rmtree(IOS_SET)
    os.makedirs(IOS_SET)
    with open(os.path.join(IOS_SET, "Contents.json"), "w") as f:
        f.write(json.dumps({"info": {"author": "xcode", "version": 1},
                            "properties": {"provides-namespace": True}}, indent=2) + "\n")
    for n, _ in icons:
        d = os.path.join(IOS_SET, n + ".imageset")
        os.makedirs(d)
        with open(os.path.join(d, n + ".svg"), "w") as f:
            f.write(ios_svg(n))
        with open(os.path.join(d, "Contents.json"), "w") as f:
            f.write(ios_contents(n))
    with open(IOS_SWIFT, "w") as f:
        f.write(swift(names))

    with open(WEB_TS, "w") as f:
        f.write(web(icons))
    print(f"exported {len(icons)} icons")


if __name__ == "__main__":
    main()
