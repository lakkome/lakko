# One-time server setup for the Lakko test stack. Run as root ON the server:
#
#   PUBLIC_IP=203.0.113.10 DOMAIN=test.lakko.me bash setup-server.sh
#
# Creates the system user, directories, the env file with freshly generated
# secrets, the per-service databases and the SFU UDP firewall rule. Idempotent:
# a re-run keeps the existing env file, so secrets and the DB password survive.
# nginx and the TLS certificate are separate steps, see README.md.
#
# Optional:
#   TURN_CONF  coturn config whose static-auth-secret auth should share
#              (default /etc/turnserver.conf; skipped when absent)
#   TURN_URIS  comma-separated TURN URIs handed to clients (required with TURN_CONF)
set -euo pipefail

PUBLIC_IP="${PUBLIC_IP:?set PUBLIC_IP to the server public IPv4}"
DOMAIN="${DOMAIN:?set DOMAIN, e.g. test.lakko.me}"
TURN_CONF="${TURN_CONF:-/etc/turnserver.conf}"
TURN_URIS="${TURN_URIS:-}"

ENV_DIR=/etc/lakko-test
ENV_FILE=$ENV_DIR/lakko.env
DBS=(auth ds discovery push_gw channels)

id lakkotest >/dev/null 2>&1 || useradd --system --home-dir /var/lib/lakko-test --shell /usr/sbin/nologin lakkotest
install -d -m 755 -o root -g root /opt/lakko-test /opt/lakko-test/bin
install -d -m 750 -o root -g lakkotest $ENV_DIR
install -d -m 750 -o lakkotest -g lakkotest /var/lib/lakko-test
install -d -m 700 -o lakkotest -g lakkotest /var/lib/lakko-test/blobs
install -d -m 755 -o root -g root /var/www/lakko-test-web

if [[ ! -f $ENV_FILE ]]; then
  umask 027
  DB_PASS=$(openssl rand -hex 32)
  WAKE_SECRET=$(openssl rand -base64 32)
  TURN_LINES="# TURN not configured"
  if [[ -f $TURN_CONF && -n $TURN_URIS ]]; then
    TURN_SECRET_B64=$(grep -E '^\s*static-auth-secret' "$TURN_CONF" | head -1 | cut -d= -f2- | tr -d ' \n' | base64 -w0)
    TURN_LINES="LAKKO_TURN_SHARED_SECRET=${TURN_SECRET_B64}
LAKKO_TURN_URIS=${TURN_URIS}"
  fi
  cat > $ENV_FILE <<EOF
# Lakko test stack ($DOMAIN). Generated by setup-server.sh. Secrets are local to this server.
RUST_LOG=info,sqlx=warn

LAKKO_AUTH_DATABASE_URL=mysql://lakko_test:${DB_PASS}@127.0.0.1:3306/lakko_test_auth
LAKKO_DS_DATABASE_URL=mysql://lakko_test:${DB_PASS}@127.0.0.1:3306/lakko_test_ds
LAKKO_DISCOVERY_DATABASE_URL=mysql://lakko_test:${DB_PASS}@127.0.0.1:3306/lakko_test_discovery
LAKKO_PUSH_GW_DATABASE_URL=mysql://lakko_test:${DB_PASS}@127.0.0.1:3306/lakko_test_push_gw
LAKKO_CHANNELS_DATABASE_URL=mysql://lakko_test:${DB_PASS}@127.0.0.1:3306/lakko_test_channels

LAKKO_SESSION_TOKEN_SECRET=$(openssl rand -base64 32)
LAKKO_TOTP_ENC_KEY=$(openssl rand -base64 32)
LAKKO_VAULT_ENC_KEY=$(openssl rand -base64 32)
LAKKO_RECOVERY_CONTACT_PEPPER=$(openssl rand -base64 32)
LAKKO_ANON_TOKEN_MASTER_SECRET=$(openssl rand -hex 32)
LAKKO_AUTH_HANDLE_PEPPER=$(openssl rand -hex 32)

LAKKO_WEBAUTHN_RP_ID=${DOMAIN}
LAKKO_WEBAUTHN_RP_NAME=Lakko (test)
LAKKO_WEBAUTHN_RP_ORIGIN=https://${DOMAIN}

${TURN_LINES}

# Proof-of-work difficulty 0 for manual testing (the proof is still requested and verified).
# Since ADR-0054 S4 the only proof left is on auth /signup/start; the other services spend
# anonymous tokens and every other auth route is limited server-side.
LAKKO_SIGNUP_POW_EFFORT_BITS=0
LAKKO_DISCOVERY_FRESH_IDENTITY_COOLDOWN_SECS=3600

LAKKO_BLOB_DIR=/var/lib/lakko-test/blobs

LAKKO_SFU_BIND=127.0.0.1:7880
LAKKO_SFU_METRICS_BIND=127.0.0.1:9641
LAKKO_SFU_JWKS_URL=http://127.0.0.1:8081/.well-known/jwks.json
LAKKO_SFU_MEDIA_BIND=0.0.0.0:43210
LAKKO_SFU_MEDIA_ADVERTISE_IP=${PUBLIC_IP}

LAKKO_GIF_PROXY_BIND=127.0.0.1:8091
# LAKKO_GIF_GIPHY_API_KEY=

# ADR-0054: the DS forwards group wakes to push-gw's internal listener
# (127.0.0.1:8092, never proxied by nginx). Both secrets hold one value.
LAKKO_PUSH_GW_INTERNAL_SECRET=${WAKE_SECRET}
LAKKO_DS_PUSH_GW_SECRET=${WAKE_SECRET}
LAKKO_DS_PUSH_GW_URL=http://127.0.0.1:8092
EOF
  chown root:lakkotest $ENV_FILE
  chmod 640 $ENV_FILE
  echo "env file created"
else
  echo "env file exists, keeping secrets"
fi

# Web Push VAPID key pair. push-gw needs the private key as PKCS#8 (a SEC1
# `BEGIN EC PRIVATE KEY` is refused); deploy.sh reads the public key file to
# build the web client.
if ! grep -q '^LAKKO_WEBPUSH_VAPID_PUBLIC_KEY_B64URL=' $ENV_FILE; then
  umask 077
  openssl ecparam -name prime256v1 -genkey -noout | openssl pkcs8 -topk8 -nocrypt -out $ENV_DIR/vapid_private.pem
  VAPID_PUB=$(openssl ec -in $ENV_DIR/vapid_private.pem -pubout -outform DER 2>/dev/null | tail -c 65 | base64 -w0 | tr '+/' '-_' | tr -d '=')
  printf '%s\n' "$VAPID_PUB" > $ENV_DIR/vapid_public.b64url
  chmod 644 $ENV_DIR/vapid_public.b64url
  chown root:lakkotest $ENV_DIR/vapid_private.pem
  chmod 640 $ENV_DIR/vapid_private.pem
  {
    echo
    echo "# Web Push (VAPID). Public key: $ENV_DIR/vapid_public.b64url"
    printf 'LAKKO_WEBPUSH_VAPID_PRIVATE_KEY_PEM="%s"\n' "$(cat $ENV_DIR/vapid_private.pem)"
    echo "LAKKO_WEBPUSH_VAPID_PUBLIC_KEY_B64URL=$VAPID_PUB"
    echo "LAKKO_WEBPUSH_VAPID_SUBJECT=https://$DOMAIN"
  } >> $ENV_FILE
  chown root:lakkotest $ENV_FILE
  chmod 640 $ENV_FILE
  echo "VAPID key pair generated"
fi

DB_PASS=$(grep -m1 '^LAKKO_AUTH_DATABASE_URL=' $ENV_FILE | sed -E 's#^.*lakko_test:([^@]+)@.*#\1#')

# The channels service arrived after the first servers were set up: an env
# file from before it keeps its secrets and gains only this line.
if ! grep -q '^LAKKO_CHANNELS_DATABASE_URL=' $ENV_FILE; then
  echo "LAKKO_CHANNELS_DATABASE_URL=mysql://lakko_test:${DB_PASS}@127.0.0.1:3306/lakko_test_channels" >> $ENV_FILE
  echo "channels database URL added to the env file"
fi

# The word vault (ADR-0049) arrived later still: an older env file gains its
# key here, generated once and then kept (regenerating it would destroy every
# vault enrolled on this stack).
if ! grep -q '^LAKKO_VAULT_ENC_KEY=' $ENV_FILE; then
  echo "LAKKO_VAULT_ENC_KEY=$(openssl rand -base64 32)" >> $ENV_FILE
  echo "word-vault key added to the env file"
fi

# Anonymous tokens (ADR-0054 decision 2) arrived later: an older env file gains
# the master secret here, generated once and then kept (regenerating it
# invalidates every token issued on this stack).
if ! grep -q '^LAKKO_ANON_TOKEN_MASTER_SECRET=' $ENV_FILE; then
  echo "LAKKO_ANON_TOKEN_MASTER_SECRET=$(openssl rand -hex 32)" >> $ENV_FILE
  echo "anonymous-token master secret added to the env file"
fi

# Sign-in by name (ADR-0054 S5) arrived later: an older env file gains the
# login-handle pepper here, generated once and then kept (regenerating it
# unbinds every login handle on this stack).
if ! grep -q '^LAKKO_AUTH_HANDLE_PEPPER=' $ENV_FILE; then
  echo "LAKKO_AUTH_HANDLE_PEPPER=$(openssl rand -hex 32)" >> $ENV_FILE
  echo "login-handle pepper added to the env file"
fi

# The DS -> push-gw wake forward (ADR-0054) arrived later: an older env file
# gains one shared secret here, written to both services' variables at once
# (a half-configured pair would stop the DS from starting).
if ! grep -q '^LAKKO_PUSH_GW_INTERNAL_SECRET=' $ENV_FILE; then
  WAKE_SECRET=$(openssl rand -base64 32)
  sed -i -e '/^LAKKO_DS_PUSH_GW_SECRET=/d' -e '/^LAKKO_DS_PUSH_GW_URL=/d' $ENV_FILE
  {
    echo
    echo "# ADR-0054: the DS forwards group wakes to push-gw's internal listener."
    echo "LAKKO_PUSH_GW_INTERNAL_SECRET=${WAKE_SECRET}"
    echo "LAKKO_DS_PUSH_GW_SECRET=${WAKE_SECRET}"
    echo "LAKKO_DS_PUSH_GW_URL=http://127.0.0.1:8092"
  } >> $ENV_FILE
  unset WAKE_SECRET
  echo "wake forward secret added to the env file"
fi

{
  for d in "${DBS[@]}"; do
    echo "CREATE DATABASE IF NOT EXISTS lakko_test_$d CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;"
  done
  for h in localhost 127.0.0.1; do
    echo "CREATE USER IF NOT EXISTS 'lakko_test'@'$h' IDENTIFIED BY '$DB_PASS';"
    echo "ALTER USER 'lakko_test'@'$h' IDENTIFIED BY '$DB_PASS';"
    for d in "${DBS[@]}"; do
      echo "GRANT ALL ON lakko_test_$d.* TO 'lakko_test'@'$h';"
    done
  done
  echo "FLUSH PRIVILEGES;"
} | mariadb
unset DB_PASS

if command -v ufw >/dev/null; then
  ufw allow 43210/udp comment 'Lakko test SFU media' >/dev/null
fi
echo "setup done"
