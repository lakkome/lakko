package me.lakko.app.calls

import android.content.Context
import android.media.AudioAttributes
import android.media.AudioManager
import android.media.MediaPlayer
import android.media.SoundPool
import android.util.Log
import java.util.concurrent.Executor
import java.util.concurrent.ExecutorService
import java.util.concurrent.Executors
import java.util.concurrent.RejectedExecutionException
import me.lakko.app.R

/**
 * Call sound cues for the Android client (S-3-A-sounds).
 *
 * Sound files live under `apps/android/app/src/main/res/raw/`
 * — generated by `tools/audio/synth-sounds.sh` from pure sine
 * tones, no third-party samples. Android's resource compiler
 * exposes them as `R.raw.<name>`; the controller maps each
 * [SoundName] to its resource id below.
 *
 * Two play modes:
 *
 * - [playOnce] — fire-and-forget short cue (`join` / `leave` /
 *   `error`). Backed by [SoundPool] which is optimised for
 *   low-latency short clips (≤ 5 s) — ideal for the 200-400 ms
 *   cues we have.
 * - [startLoop] / [stopLoop] — repeating cue
 *   (`ringtone-incoming` / `ringback-outgoing`). Backed by
 *   [MediaPlayer] with `isLooping = true` since these are
 *   multi-second loops that exceed [SoundPool]'s practical
 *   memory budget.
 *
 * ## ConnectionService interaction
 *
 * The system ringtone for an *incoming* call is owned by the
 * `ConnectionService` layer (3a-pod-followup) — that's a
 * Telephony notification, not an in-app cue. This controller
 * handles *in-app* sounds that fire **after** the call is
 * answered.
 *
 * ## Silent-mode politeness
 *
 * Both `SoundPool` and `MediaPlayer` are configured with the
 * [AudioAttributes.USAGE_VOICE_COMMUNICATION_SIGNALLING] usage
 * which honours the Do-Not-Disturb / silent-mode settings the
 * user picked at the OS level. The user does not need to
 * mute the app separately.
 *
 * ## Thread safety
 *
 * The public surface is called from the main thread, and nothing
 * on it may block that thread: preparing a [MediaPlayer] waits on
 * the media service, which held the main thread long enough for the
 * system's "isn't responding" dialog during a call. Every
 * [MediaPlayer] call therefore runs in order on [worker].
 */
public class CallSoundController internal constructor(
    context: Context,
    private val volume: Float,
    private val worker: Executor,
) {

    public constructor(context: Context, volume: Float = 1.0f) :
        this(context, volume, newWorker())

    /**
     * Pinned set of cue names. Same identifiers as the web
     * (`SoundName` in `CallSoundController.ts`) and iOS
     * controllers — keeping them in lockstep lets the wiring
     * layer share a single trigger map across platforms.
     */
    public enum class SoundName(internal val rawId: Int) {
        RINGTONE_INCOMING(R.raw.ringtone_incoming),
        RINGBACK_OUTGOING(R.raw.ringback_outgoing),
        JOIN(R.raw.join),
        LEAVE(R.raw.leave),
        ERROR(R.raw.error),
        ;

        internal val isLooping: Boolean
            get() = when (this) {
                RINGTONE_INCOMING, RINGBACK_OUTGOING -> true
                JOIN, LEAVE, ERROR -> false
            }
    }

    private val appCtx: Context = context.applicationContext

    /**
     * `SoundPool` is optimised for short clips played from a
     * pool of pre-loaded buffers. Max-stream count = 4 covers
     * "user A and user B join within the same 200 ms window"
     * without dropping samples — anything beyond that is fine
     * to drop (you can't perceptually distinguish more than
     * a couple of stacked cues anyway).
     */
    private val soundPool: SoundPool = SoundPool.Builder()
        .setMaxStreams(MAX_STREAMS)
        .setAudioAttributes(audioAttributes())
        .build()

    /** Map cue → SoundPool sample id once loading completes. */
    private val sampleIds: MutableMap<SoundName, Int> = HashMap()

    /** MediaPlayers cached per looping cue. */
    private val loopPlayers: MutableMap<SoundName, MediaPlayer> = HashMap()

    init {
        // Eagerly load the short cues — `playOnce` from a
        // not-yet-loaded sample silently no-ops on Android, so
        // pre-loading avoids "first cue is missing" UX bugs.
        for (cue in SoundName.values()) {
            if (!cue.isLooping) {
                sampleIds[cue] = soundPool.load(appCtx, cue.rawId, 1)
            }
        }
    }

    /**
     * Play [name] once. Calling repeatedly within the
     * [SoundPool]'s ring (4 simultaneous streams) stacks
     * cleanly; beyond that, oldest sample is evicted.
     */
    public fun playOnce(name: SoundName) {
        if (name.isLooping) {
            Log.w(TAG, "playOnce called on looping cue $name; ignoring")
            return
        }
        val id = sampleIds[name]
        if (id == null) {
            Log.w(TAG, "sample $name not loaded yet")
            return
        }
        // priority=0 (all cues equal), rate=1.0 (no pitch shift).
        soundPool.play(id, volume, volume, 0, 0, 1.0f)
    }

    /**
     * Start [name] looping. No-op if the same cue is already
     * playing — keeps the pattern (2 s on / 4 s off) steady.
     */
    public fun startLoop(name: SoundName) {
        if (!name.isLooping) {
            Log.w(TAG, "startLoop on non-looping cue $name")
            return
        }
        onWorker { startLoopNow(name) }
    }

    private fun startLoopNow(name: SoundName) {
        loopPlayers[name]?.let { existing ->
            if (existing.isPlaying) return
            existing.start()
            return
        }
        val player = MediaPlayer().apply {
            setAudioAttributes(audioAttributes())
            try {
                appCtx.resources.openRawResourceFd(name.rawId).use { afd ->
                    setDataSource(afd.fileDescriptor, afd.startOffset, afd.length)
                }
                setVolume(volume, volume)
                isLooping = true
                prepare()
                start()
            } catch (e: Exception) {
                Log.e(TAG, "startLoop($name) failed", e)
                release()
                return
            }
        }
        loopPlayers[name] = player
    }

    /** Stop [name]'s loop; a subsequent [startLoop] builds a fresh
     *  player, so it begins cleanly at the burst boundary. */
    public fun stopLoop(name: SoundName) {
        onWorker { stopLoopNow(name) }
    }

    private fun stopLoopNow(name: SoundName) {
        loopPlayers.remove(name)?.let { player ->
            try {
                if (player.isPlaying) player.stop()
            } catch (e: IllegalStateException) {
                Log.w(TAG, "stopLoop($name) failed", e)
            }
            player.release()
        }
    }

    /** Stop every active cue (loops + one-shots). Called on
     *  `endCall()` / `Activity.onPause()`. */
    public fun stopAll() {
        soundPool.autoPause()
        onWorker { SoundName.values().forEach { stopLoopNow(it) } }
    }

    /** Release every native resource. Call from `onCleared()`
     *  / `onDestroy()` — without this, the SoundPool + each
     *  MediaPlayer leak their AudioTrack handles. */
    public fun release() {
        stopAll()
        soundPool.release()
        sampleIds.clear()
        (worker as? ExecutorService)?.shutdown()
    }

    /** A cue that arrives after [release] has nothing left to play. */
    private fun onWorker(work: () -> Unit) {
        try {
            worker.execute(work)
        } catch (e: RejectedExecutionException) {
            Log.w(TAG, "call sound after release", e)
        }
    }

    private fun audioAttributes(): AudioAttributes =
        AudioAttributes.Builder()
            // VOICE_COMMUNICATION_SIGNALLING tells the OS
            // "this is a call-progress cue", so it honours
            // DND / silent settings the way the user expects
            // and ducks music underneath rather than
            // shoulder-stopping it.
            .setUsage(AudioAttributes.USAGE_VOICE_COMMUNICATION_SIGNALLING)
            .setContentType(AudioAttributes.CONTENT_TYPE_SONIFICATION)
            .build()

    private companion object {
        private const val TAG: String = "CallSoundController"
        private const val MAX_STREAMS: Int = 4

        private fun newWorker(): ExecutorService =
            Executors.newSingleThreadExecutor { work -> Thread(work, "lakko-call-sounds") }

        // Reference-only assertion that AudioManager exists
        // on the runtime; if Android ever splits audio out of
        // the system services tree, this catches it early
        // at compile time.
        @Suppress("unused")
        private val audioManagerClass: Class<AudioManager> = AudioManager::class.java
    }
}
