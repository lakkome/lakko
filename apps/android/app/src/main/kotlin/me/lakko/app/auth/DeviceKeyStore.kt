package me.lakko.app.auth

import android.content.Context
import android.os.Build
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.security.keystore.StrongBoxUnavailableException
import java.security.ProviderException
import java.io.File
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Keystore-wrap-key + on-disk envelope storage for the device
 * root key.
 *
 * ## Threat model
 *
 * The device root key is the bottom of the local data-encryption
 * hierarchy: every MLS group state, every Room-encrypted column,
 * every Compose-side draft sits underneath it (1.15f's
 * `EncryptedFile` MLS persistence). If an attacker reads the
 * device root key, the local secrets are over.
 *
 * Android Keystore is the only **hardware-isolated** option:
 *
 *   * On devices with StrongBox (Pixel 3+, Galaxy S20+, many 2020+
 *     mid-range) the wrap key lives in a separate tamper-resistant
 *     chip; even a root-compromised OS cannot exfiltrate it.
 *   * On devices without StrongBox we fall back to TEE-backed
 *     keystore — the wrap key still never enters the app process
 *     heap, but the TEE shares physical memory with the OS.
 *
 * ## Envelope scheme
 *
 * 1. At first login on this device, [putDeviceKey] is called with
 *    the 32-byte device root key derived from
 *    [deriveDeviceRootKey].
 * 2. We get-or-create a Keystore-resident AES-256-GCM wrap key
 *    under alias [WRAP_KEY_ALIAS]. Properties:
 *    * `BLOCK_MODE_GCM` + `ENCRYPTION_PADDING_NONE` — standard
 *      AEAD construction.
 *    * `setIsStrongBoxBacked(true)` when available (we ignore
 *      [StrongBoxUnavailableException] and re-issue without the
 *      flag on devices missing the chip).
 *    * `setUserAuthenticationRequired(false)` — Lakko needs to
 *      decrypt local state to deliver push-triggered MLS reads
 *      without bouncing the user through a biometric prompt.
 *      Equivalent to the WebCrypto `extractable: false` posture
 *      on the web side (background access without re-auth).
 * 3. We encrypt the device root key bytes with that key. The IV
 *    is generated by the Keystore Cipher (randomized).
 * 4. The opaque `(iv || ciphertext || tag)` blob is persisted to
 *    a per-account file under `getNoBackupFilesDir()/lakko-device-keys/`.
 *    `noBackup` matters: device root keys are device-bound; an
 *    auto-restore from Google's adb cloud backup must not carry
 *    them between devices.
 *
 * [getDeviceKey] reverses the process; [deleteDeviceKey] wipes
 * both the on-disk envelope and (when no other account remains)
 * the Keystore master.
 *
 * ## Persistence layout
 *
 * ```text
 *   filesNoBackupDir/lakko-device-keys/
 *     <accountIdB64>.bin     12-byte IV | ciphertext | 16-byte tag
 * ```
 *
 * One file per account. `accountIdB64` is the base64 form of the
 * raw 16-byte UUIDv7 — already URL-safe-free of `\0`, but we
 * additionally `.replace("/", "_")` to stay file-system-safe on
 * every Android storage backend (some legacy implementations
 * choke on `/`).
 *
 * ## Why not [androidx.security.crypto.EncryptedSharedPreferences]?
 *
 * Jetpack Security's `EncryptedSharedPreferences` is **deprecated
 * since 2024** (the `androidx.security:security-crypto` library
 * is on indefinite maintenance, the underlying `tink-android`
 * had repeated CVEs and Google's official guidance is now
 * "use the platform Keystore directly"). The 30-line
 * implementation below is the platform path, audited against the
 * same Keystore APIs Jetpack Security wrapped.
 *
 * ## Host-JVM tests
 *
 * The class loads the `AndroidKeyStore` provider, which only
 * exists on a real device or emulator. Host-side `:app:testDebugUnitTest`
 * therefore cannot exercise these methods; coverage comes from
 * 1.15d4's instrumented signup-flow tests.
 */
public object DeviceKeyStore {

    /** AES-256-GCM in [Cipher] notation. */
    private const val AES_GCM_NOPAD = "AES/GCM/NoPadding"

    /** GCM IV is 96 bits per NIST SP 800-38D — also the default
     *  Keystore Cipher generates when not given an explicit IV. */
    private const val GCM_IV_LEN = 12

    /** GCM auth tag length, in bits. 128 is the maximum and the
     *  recommended value. */
    private const val GCM_TAG_BITS = 128

    /** Keystore alias for the wrap key. Versioned so a future
     *  rotation has somewhere to go. */
    public const val WRAP_KEY_ALIAS: String = "me.lakko.device-key-wrap.v1"

    /** Provider name. The `AndroidKeyStore` constant is exposed as
     *  a public string by the Android SDK but referenced as a
     *  string literal in countless code samples; spell it out
     *  here to avoid the import. */
    private const val ANDROID_KEYSTORE = "AndroidKeyStore"

    /** Subdirectory under the app's no-backup files dir where the
     *  per-account envelope files live. */
    private const val ENVELOPE_DIR = "lakko-device-keys"

    /**
     * Persist [rootKey] for [accountIdB64].
     *
     * Existing record (if any) is overwritten — same posture as
     * `putDeviceKey` on the web side. The caller is responsible
     * for [java.util.Arrays.fill]'ing [rootKey] afterwards;
     * `putDeviceKey` keeps no reference past the wrap call.
     *
     * @throws java.io.IOException if the on-disk write fails.
     * @throws java.security.GeneralSecurityException if Keystore
     *         operations fail in a non-recoverable way.
     */
    public fun putDeviceKey(
        context: Context,
        accountIdB64: String,
        rootKey: ByteArray,
    ) {
        require(rootKey.size == EXPECTED_ROOT_KEY_LEN) {
            "device root key must be $EXPECTED_ROOT_KEY_LEN bytes (got ${rootKey.size})"
        }
        val wrap = getOrCreateWrapKey()
        val cipher = Cipher.getInstance(AES_GCM_NOPAD)
        cipher.init(Cipher.ENCRYPT_MODE, wrap)
        // Keystore-generated IV — we don't pass our own; instead
        // we read it back after init. Pulling our own IV from a
        // host CSPRNG would also be safe (96 bits, GCM IV-reuse
        // bound is 2^32 messages per key), but the Keystore path
        // is one less moving part to audit.
        val iv = cipher.iv
        check(iv.size == GCM_IV_LEN) {
            "unexpected GCM IV length from Keystore: ${iv.size}"
        }
        val ciphertext = cipher.doFinal(rootKey)

        val out = ByteArray(GCM_IV_LEN + ciphertext.size)
        System.arraycopy(iv, 0, out, 0, GCM_IV_LEN)
        System.arraycopy(ciphertext, 0, out, GCM_IV_LEN, ciphertext.size)

        envelopeFile(context, accountIdB64).writeBytes(out)
    }

    /**
     * Read and unwrap the device root key for [accountIdB64].
     *
     * Returns `null` if no envelope is on disk for that account
     * — same shape as the web's `getDeviceKey` returning `null`.
     * Keystore failures (revoked / corrupted wrap key) surface
     * as [java.security.GeneralSecurityException].
     */
    public fun getDeviceKey(context: Context, accountIdB64: String): ByteArray? {
        val file = envelopeFile(context, accountIdB64)
        if (!file.exists()) return null
        val blob = file.readBytes()
        if (blob.size <= GCM_IV_LEN) {
            // Truncated file — surface as null rather than crash.
            // Callers will treat it as "no key on this device"
            // and trigger a re-derivation through login.
            return null
        }
        val iv = blob.copyOfRange(0, GCM_IV_LEN)
        val ciphertext = blob.copyOfRange(GCM_IV_LEN, blob.size)

        val wrap = getOrCreateWrapKey()
        val cipher = Cipher.getInstance(AES_GCM_NOPAD)
        cipher.init(
            Cipher.DECRYPT_MODE,
            wrap,
            GCMParameterSpec(GCM_TAG_BITS, iv),
        )
        return cipher.doFinal(ciphertext)
    }

    /**
     * Erase the device root key for [accountIdB64]. No-op if the
     * envelope file is absent. The Keystore wrap key is left
     * intact — other accounts on the same device may still need
     * it, and re-creating it would require re-wrapping every
     * surviving envelope.
     */
    public fun deleteDeviceKey(context: Context, accountIdB64: String) {
        envelopeFile(context, accountIdB64).delete()
    }

    /**
     * Seal [plaintext] with the Keystore-resident wrap key (AES-256-GCM,
     * `iv(12) | ciphertext+tag`). For the small per-device secrets that get
     * the device root key's protection without being one (the ADR-0074
     * recall record). The key never leaves the Keystore.
     */
    internal fun sealWithDeviceKey(plaintext: ByteArray): ByteArray {
        val cipher = Cipher.getInstance(AES_GCM_NOPAD)
        cipher.init(Cipher.ENCRYPT_MODE, getOrCreateWrapKey())
        val iv = cipher.iv
        check(iv.size == GCM_IV_LEN) { "unexpected GCM IV length from Keystore: ${iv.size}" }
        val ciphertext = cipher.doFinal(plaintext)
        val out = ByteArray(GCM_IV_LEN + ciphertext.size)
        System.arraycopy(iv, 0, out, 0, GCM_IV_LEN)
        System.arraycopy(ciphertext, 0, out, GCM_IV_LEN, ciphertext.size)
        return out
    }

    /** Open a blob [sealWithDeviceKey] made; `null` for a truncated one.
     *  A blob that does not authenticate throws. */
    internal fun openWithDeviceKey(blob: ByteArray): ByteArray? {
        if (blob.size <= GCM_IV_LEN) return null
        val cipher = Cipher.getInstance(AES_GCM_NOPAD)
        cipher.init(
            Cipher.DECRYPT_MODE,
            getOrCreateWrapKey(),
            GCMParameterSpec(GCM_TAG_BITS, blob.copyOfRange(0, GCM_IV_LEN)),
        )
        return cipher.doFinal(blob, GCM_IV_LEN, blob.size - GCM_IV_LEN)
    }

    // -----------------------------------------------------------------
    // Internal: wrap-key lifecycle
    // -----------------------------------------------------------------

    /**
     * Load (or generate on first call) the Keystore-resident
     * AES-256-GCM wrap key under [WRAP_KEY_ALIAS].
     *
     * StrongBox is preferred when the device exposes it. On
     * devices without the chip the Keystore raises
     * [StrongBoxUnavailableException] from `generateKey` — we
     * catch and retry without the flag. The TEE path is still
     * orders of magnitude safer than holding the bytes in app
     * memory.
     */
    private fun getOrCreateWrapKey(): SecretKey {
        val ks = KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }
        ks.getKey(WRAP_KEY_ALIAS, null)?.let { existing ->
            return existing as SecretKey
        }
        return generateWrapKey()
    }

    private fun generateWrapKey(): SecretKey {
        val builder = KeyGenParameterSpec.Builder(
            WRAP_KEY_ALIAS,
            KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
        )
            .setKeySize(EXPECTED_ROOT_KEY_LEN * 8)
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .setRandomizedEncryptionRequired(true)
            // `false` because Lakko must decrypt local MLS state
            // for push-triggered background reads without
            // bouncing the user through a biometric prompt.
            // Mirror of the web `extractable: false` posture:
            // the key bytes never leave the secure enclave, but
            // they're addressable by the app process at any time.
            .setUserAuthenticationRequired(false)

        val strongBoxSpec = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.P) {
            // `setIsStrongBoxBacked` was added in API 28. Our
            // minSdk is 26; gate the call so the build still
            // assembles for older targets if we ever lower it
            // back. The reflect-style call avoids a `lint:NewApi`.
            builder.setIsStrongBoxBacked(true).build()
        } else {
            null
        }

        val kg = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEYSTORE)
        if (strongBoxSpec != null) {
            try {
                kg.init(strongBoxSpec)
                return kg.generateKey()
            } catch (_: StrongBoxUnavailableException) {
                // Device claims API 28+ but has no StrongBox
                // chip — fall through to the TEE path. The
                // unwrap operation against a TEE-backed key is
                // identical from the app's point of view; the
                // only delta is the hardware-isolation boundary.
            } catch (_: ProviderException) {
                // Newer keystore2 builds report a missing StrongBox
                // as `ProviderException("Failed to generate key")`
                // (HARDWARE_TYPE_UNAVAILABLE) rather than the typed
                // exception, observed on an API 35 emulator. Same
                // fallback.
            }
            // `setIsStrongBoxBacked(true)` above MUTATED the builder, so
            // the TEE retry must clear the flag explicitly or it fails
            // exactly like the StrongBox attempt did.
            builder.setIsStrongBoxBacked(false)
        }
        kg.init(builder.build())
        return kg.generateKey()
    }

    // -----------------------------------------------------------------
    // Internal: file-system layout
    // -----------------------------------------------------------------

    /**
     * Per-account envelope file path. `noBackupFilesDir` is the
     * canonical no-restore-from-cloud directory; device root
     * keys must NOT travel between devices via Google's auto-
     * backup, even if the user opts in.
     */
    private fun envelopeFile(context: Context, accountIdB64: String): File {
        val dir = File(context.noBackupFilesDir, ENVELOPE_DIR)
        if (!dir.exists() && !dir.mkdirs()) {
            // Don't throw here — the eventual `writeBytes` call
            // will surface the real I/O error with a useful
            // stack frame.
        }
        // Replace base64 `/` with `_` so the segment is filesystem-
        // safe on every Android storage backend. `+` and `=` are
        // both legal in filenames on every Android FS we ship to.
        val safe = accountIdB64.replace("/", "_")
        return File(dir, "$safe.bin")
    }

    /** Expected length of the AES-256 device root key. */
    private const val EXPECTED_ROOT_KEY_LEN: Int = 32
}
